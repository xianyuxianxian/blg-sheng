/** 「上卦|下卦」→ 文王卦序（1–64）。 */
const KING_WEN_BY_TRIGRAMS = new Map<string, number>(
  KING_WEN_TRIGRAMS.map(([shang, xia], index) => [`${shang}|${xia}`, index + 1]),
);

/**
 * 上下经卦 → 文王卦序（1–64，即通行本卦号）。
 *
 * @param shangGua 上卦（外卦）
 * @param xiaGua 下卦（内卦）
 */
export function hexagramNumber(shangGua: Trigram, xiaGua: Trigram): number {
  const number = KING_WEN_BY_TRIGRAMS.get(`${shangGua}|${xiaGua}`);
  if (!number) {
    // 8×8 组合穷尽 64 卦，走不到这里
    throw new Error(`未知卦象组合：${shangGua}上${xiaGua}下`);
  }
  return number;
}

/**
 * 上下经卦 → 卦符（U+4DC0–U+4DFF 中的对应字符，如 乾→䷀、晋→䷢）。
 *
 * 卦符是装饰性图形，调用处应配 `aria-hidden`，卦名文本已承担语义。
 */
export function hexagramSymbol(shangGua: Trigram, xiaGua: Trigram): string {
  return String.fromCodePoint(HEXAGRAM_UNICODE_BASE + hexagramNumber(shangGua, xiaGua) - 1);
}
